'use strict';
const assert=require('node:assert/strict');
const Aqua=require('../aqua_sim'),Codec=require('../motion_v2');
const {issueBinaryMotion,server}=require('../server');
let count=0;
function ok(v,n){assert.ok(v,n);console.log('PASS',n);count++}
function game(seed=4411){const s=Aqua.create();s.newMatch({seed,mode:'free',competitorCount:200,maxTotalFish:200,npcCount:0,miniFishCount:30,slots:{fish:[{pid:'me',sp:'guppy'}]}});return s}
const input={me:{mv:{x:0,y:0,z:0}}},s=game();
ok(s.plank.length===320&&s.plank.filter(p=>p.alive).length===240,'six finite floating patches with 240 starter pellets');
ok(s.foodPatches.length===6,'surface food patches are separately identifiable');
const f=s.fishes[0],p=s.plank[0],id=p.patchId;
f.x=p.x;f.y=p.y;f.z=p.z;f.prot=0;
s.step(input,1/60);
ok(f.mass>100&&!p.alive&&p.x===0&&p.y===0&&p.z===0,'eaten pellet disappears and rewards mass');
const left=s.plank.filter(z=>z.alive&&z.patchId===id).length;
for(let i=0;i<5;i++)s.step(input,1/30);
ok(s.plank.filter(z=>z.alive&&z.patchId===id).length<=left,'same patch is never replenished');
const oldIds=new Set(s.foodPatches.map(p=>p.id)),next=s.snapshot().nextFoodPatchAt;
s.step(input,next-s.t+.01);
ok(s.foodPatches.some(p=>!oldIds.has(p.id)),'new patches appear periodically');
ok(s.plank.filter(p=>p.alive).length<=320,'active food stays below capacity');
const copy=Aqua.create();copy.restore(JSON.parse(JSON.stringify(s.snapshot())));
ok(JSON.stringify(copy.snapshot())===JSON.stringify(s.snapshot()),'food timers and patch IDs survive snapshots');
const high=game(22),low=game(22);
for(const p of high.npcs.slice(0,1))p.alive=false;
for(const p of low.npcs.slice(0,25))p.alive=false;
high.step(input,1/60);low.step(input,1/60);
ok(low.miniSchool.birthT<high.miniSchool.birthT,'lower school population gives faster births');
const empty=game(55);for(const p of empty.npcs)p.alive=false;
for(let i=0;i<32;i++)empty.step(input,1/30);
ok(empty.npcs.some(p=>p.alive),'school recovers even from zero survivors');
ok(empty.npcs.length===30,'school never exceeds thirty slots');
const records=[],net=game(917),ws={closed:false,socket:{writableLength:0},sendBinary:b=>records.push(Codec.decode(b))};
const user={pid:'me',role:'fish',ws},room={sim:net,users:new Map([['me',user]]),tick:1};
issueBinaryMotion(room,1000,false,true,false);
ok(records[0].plank.some(([i,v])=>i===0&&v[1]>0),'live binary pellet record sent');
Object.assign(net.plank[0],{alive:false,x:0,y:0,z:0});
room.tick=2;issueBinaryMotion(room,1200,false,true,false);
ok(records[1].plank.some(([i,v])=>i===0&&v.every(n=>n===0)),'consumed food tombstone reaches multiplayer client');
room.tick=3;issueBinaryMotion(room,1400,false,true,false);
ok(!records[2].plank.some(([i])=>i===0),'tombstone is sent only when entity changes');
server.close();
console.log(count+' food ecology checks passed');
