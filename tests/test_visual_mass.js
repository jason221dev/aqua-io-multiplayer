'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const html=fs.readFileSync(require('node:path').join(__dirname,'../index.html'),'utf8');
const start=html.indexOf('  const massBlend=1-Math.exp(-dt*7);');
const end=html.indexOf('  fishes.forEach((f,i)=>{const e=fm[i];if(!e)return;',start);
assert(start>=0&&end>start,'visual-mass update must run before per-model render loop');
const update=html.slice(start,end);
assert(!update.includes('fm['),'must not skip instanced fish with no dedicated model');
const all=Array.from({length:200},(_,i)=>({mass:i===0?100:i%3===0?1200:600,displayMass:100,alive:true}));
const ctx={dt:1/60,fishes:all};
for(let n=0;n<60;n++)vm.runInNewContext(update,ctx,{timeout:1000});
assert.equal(all[0].displayMass,100,'starter size must remain unchanged');
assert(all[1].displayMass>590,'instanced remote competitor must approach actual size');
assert(all[3].displayMass>1180,'largest fish must appear noticeably larger');
const radius=m=>5+Math.sqrt(m)*.95;
assert(radius(all[3].displayMass)>radius(all[0].displayMass)*1.9,'visible radius must match mass growth');
assert(html.includes('R.scale.setScalar(rad(f.displayMass||f.mass)*1.05)'), 'cartoon instanced fish must consume displayMass');
console.log('PASS: all 200 competitors grow visually, including fish using GPU instancing');
