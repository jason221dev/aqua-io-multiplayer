'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const from=html.indexOf('const rivalDetailBudget=');
const to=html.indexOf('function rebuild3D(){',from);
assert(from>0&&to>from);
const selectContext={Uint8Array,Float64Array,Math};
vm.runInNewContext(html.slice(from,to)+'\nthis.pick=selectRivalNearDetail;this.budget=rivalDetailBudget;',selectContext);
function picked(rows,models,center,eye,cap){
 const b=selectContext.pick(rows,models,center,eye,cap);
 return Array.from(b.selected.slice(0,rows.length)).map((x,i)=>x?i:-1).filter(i=>i>=0);
}
let rows=Array.from({length:200},(_,i)=>({x:i*.12,y:10,z:0,alive:true,sp:'guppy',mass:100}));
let models=Array(200).fill(null);models[0]={};
let ids=picked(rows,models,{x:10,y:10,z:0},{x:0,y:-10,z:0},20);
assert.equal(ids.length,20,'hard budget respected for 199 rivals in single crowded camera region');
assert(!ids.includes(0),'local player is not instanced');
assert(ids.every(i=>rows[i].alive),'never includes dead fish');
assert.equal(selectContext.budget.candidates,199,'all 199 rivals are considered for a render LOD');
assert(ids.includes(1)&&ids.includes(2),'closest rival receives high detail before further rivals');
assert.deepEqual(ids,picked(rows,models,{x:10,y:10,z:0},{x:0,y:-10,z:0},20),'stable selection without roster reordering');
rows[2].alive=false;models[3]={};ids=picked(rows,models,{x:10,y:10,z:0},{x:0,y:-10,z:0},20);
assert(!ids.includes(2)&&!ids.includes(3),'dead and locally rendered fish excluded');
rows=Array.from({length:200},(_,i)=>({x:2000+i*15,y:150,z:0,alive:true}));
models=Array(200).fill(null);ids=picked(rows,models,{x:2000,y:150,z:0},{x:2000,y:-150,z:0},20);
assert(ids.length>0&&ids.length<=20,'only near candidates get high detail');
assert(ids.every(i=>rows[i].x<2650),'far fish use lower LOD, not dropped');
rows=Array.from({length:801},(_,i)=>({x:i*.04,y:10,z:0,alive:true}));
models=Array(rows.length).fill(null);ids=picked(rows,models,{x:0,y:10,z:0},{x:0,y:-10,z:0},20);
assert.equal(ids.length,20,'dynamic capacity supports larger network rosters');
assert(selectContext.budget.selected.length>=rows.length,'LOD selection buffer grows safely');
const governorFrom=html.indexOf('const qualityGovernor=');
const governorTo=html.indexOf('function resize(){',governorFrom);
const governorContext={renderer:{},state:'play',document:{hidden:false},Math,renderQualityScale:1,resizeCount:0,resize(){governorContext.resizeCount++}};
vm.runInNewContext(html.slice(governorFrom,governorTo)+'\nthis.qTick=applyRenderQuality;this.quality=()=>renderQualityScale;',governorContext);
for(let i=0;i<36;i++)governorContext.qTick(.085,i*85);
assert(governorContext.quality()<=.82,'extreme 12 FPS state should trigger an early resolution reduction');
const reduced=governorContext.quality();
for(let i=0;i<80;i++)governorContext.qTick(.0167,5000+i*16.7);
assert(governorContext.quality()<=reduced+.041,'short transient good performance cannot immediately restore full resolution');
assert(html.includes("antialias:!coarsePointer"),'mobile hardware multisample antialias disabled');
assert(html.includes('recordSplashPerformance('),'opt-in profiling captures on-device frame rate and draw counts');
console.log('PASS splashdown near-LOD budget (200+ fish), deterministic priority, larger rosters, recovery governor, mobile MSAA, diagnostics');
